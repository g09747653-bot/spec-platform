/**
 * Веер с потолком — единственный примитив параллельности планирования (А-51 п.3, находка А-51).
 *
 * **Зачем.** Исполнительская полоса выжата: замер А-44 дал 9,72× по конвейеру при 97,2% идеала.
 * Потолок теперь ставит ПЛАНИРОВАНИЕ, и ставит его один цикл: десять независимых заданий
 * писались десятью модельными вызовами ПО ОЧЕРЕДИ при нулевых зависимостях между ними. Это не
 * архитектурное ограничение — это `for … await` в одном месте.
 *
 * **Почему с потолком, а не `Promise.all`.** Цепочка провайдеров перебирает ВСЕ свои звенья на
 * каждом вызове (`chain.ts`): при красном первом звене шестнадцать одновременных заданий дают
 * шестнадцать одновременных запросов на КАЖДОМ звене по очереди, а не шестнадцать запросов всего.
 * Ограничивать надо вызовы `generate`, и ограничивать заранее, а не после первого отказа.
 *
 * **Порядок результатов — порядок входа, всегда.** Это и есть контракт, ради которого веер вообще
 * можно поставить в планирование: план читает человек, и «задача 7» обязана остаться седьмой,
 * какой бы вызов ни ответил первым.
 */

/**
 * Сколько модельных вызовов планирования идёт разом по умолчанию.
 *
 * Пять, и число выбрано не смелостью: ширина подписки измерена на исполнителях (десять без
 * троттла), но там одновременность стоит контейнеров, а здесь — сетевых ходов, и каждый ход при
 * красном звене умножается на длину цепочки. Пять — это заведомо ниже измеренной ширины и заведомо
 * выше единицы, с которой мы жили. Оператор вправе поставить своё через `LOOP_INTAKE_CONCURRENCY`.
 */
export const DEFAULT_INTAKE_CONCURRENCY = 5;

/**
 * `map`, у которого одновременно в полёте не больше `limit` работ.
 *
 * Отказ одной работы — отказ всего веера, как у `Promise.all`: планирование, потерявшее задание,
 * не «план с дыркой», а отсутствие плана. Уже запущенные при этом доигрывают — обрывать чужой
 * сетевой ход нечем и незачем.
 */
export async function mapWithLimit<In, Out>(
  items: readonly In[],
  limit: number,
  run: (item: In, index: number) => Promise<Out>,
): Promise<Out[]> {
  if (items.length === 0) return [];

  const width = Math.max(1, Math.min(Math.floor(limit), items.length));
  const results = new Array<Out>(items.length);
  let next = 0;

  const worker = async (): Promise<void> => {
    for (;;) {
      const index = next;
      next += 1;
      if (index >= items.length) return;

      /* `items[index]` существует по построению: индекс взят из длины того же массива. */
      results[index] = await run(items[index] as In, index);
    }
  };

  await Promise.all(Array.from({ length: width }, () => worker()));

  return results;
}
